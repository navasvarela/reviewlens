import { mkdir, mkdtemp, rm, writeFile } from "node:fs/promises"
import { tmpdir } from "node:os"
import { dirname, join } from "node:path"
import { commitShaSchema } from "@lens/review-model"
import type { ChangedFile, CommitSha } from "@lens/review-model"
import { afterAll, beforeAll, describe, expect, it } from "vitest"
import { analyzeChangedFiles } from "./analyzeChangedFiles.ts"
import { runGit } from "./git.ts"

const COMMITTER_ENV = {
  GIT_AUTHOR_NAME: "Test",
  GIT_AUTHOR_EMAIL: "test@example.com",
  GIT_COMMITTER_NAME: "Test",
  GIT_COMMITTER_EMAIL: "test@example.com",
}

const PRICE_FN = `pub fn total(items: &[Item]) -> u64 {
    let subtotal = items.iter().map(|item| item.price * item.quantity).sum::<u64>();
    subtotal + shipping(subtotal)
}
`

describe("analyzeChangedFiles", () => {
  let repoDir = ""
  let files: ChangedFile[] = []

  const git = (...args: string[]): Promise<string> => runGit(args, { cwd: repoDir, env: COMMITTER_ENV })
  const write = async (path: string, content: string): Promise<void> => {
    await mkdir(dirname(join(repoDir, path)), { recursive: true })
    await writeFile(join(repoDir, path), content)
  }
  const commit = async (): Promise<CommitSha> => {
    await git("add", "--all")
    await git("commit", "--quiet", "--message", "change")
    return commitShaSchema.parse((await git("rev-parse", "HEAD")).trim())
  }
  const file = (path: string): ChangedFile | undefined => files.find((changed) => changed.diff.path === path)

  beforeAll(async () => {
    repoDir = await mkdtemp(join(tmpdir(), "lens-analyze-"))
    await git("init", "--quiet")
    await write("Cargo.lock", "version = 3\n")
    await write("src/cart.rs", `use crate::item::Item;\n\n${PRICE_FN}\npub fn empty() -> bool { true }\n`)
    await write("src/old_name.py", "def greet(name):\n    return 'hi ' + name\n\ndef other():\n    return 1\n")
    await write("src/schema.ts", "// @generated by codegen\nexport type A = 1\n")
    await write("README.md", "# demo\n")
    const base = await commit()

    await write("Cargo.lock", "version = 4\n")
    await write("src/cart.rs", "use crate::item::Item;\n\npub fn empty() -> bool {\n    true\n}\n")
    await write("src/pricing.rs", `use crate::item::Item;\n\n${PRICE_FN}`)
    await git("mv", "src/old_name.py", "src/new_name.py")
    await write("src/new_name.py", "def greet(name):\n    return 'hello ' + name\n\ndef other():\n    return 1\n")
    await write("src/schema.ts", "// @generated by codegen\nexport type A = 2\n")
    await write("README.md", "# demo\n\nMore.\n")
    const head = await commit()

    files = await analyzeChangedFiles(repoDir, base, head)
  })

  afterAll(async () => {
    await rm(repoDir, { recursive: true, force: true })
  })

  it("marks lockfiles and generated files as noise and skips their syntax analysis", () => {
    expect(file("Cargo.lock")).toMatchObject({ noise: { kind: "lockfile" }, syntax: { status: "unsupportedLanguage" } })
    expect(file("src/schema.ts")).toMatchObject({
      noise: { kind: "generated" },
      syntax: { status: "skipped", reason: "generated file" },
    })
  })

  it("leaves unsupported languages to the hunk view", () => {
    expect(file("README.md")).toMatchObject({ noise: null, syntax: { status: "unsupportedLanguage" } })
  })

  it("tracks a function moved between files and a reformatted one left behind", () => {
    const cart = file("src/cart.rs")?.syntax
    expect(cart).toMatchObject({ status: "analyzed", language: "rust" })
    expect(cart?.status === "analyzed" ? cart.units : []).toEqual(
      expect.arrayContaining([
        expect.objectContaining({ qualifiedName: "total", change: expect.objectContaining({ kind: "movedOut", to: { path: "src/pricing.rs", qualifiedName: "total" } }) }),
        expect.objectContaining({ qualifiedName: "empty", change: expect.objectContaining({ kind: "modified", weight: "formattingOnly" }) }),
      ]),
    )
    expect(file("src/pricing.rs")?.syntax).toMatchObject({
      status: "analyzed",
      units: [
        { qualifiedName: "(module scope)", change: { kind: "added" } },
        { qualifiedName: "total", change: { kind: "movedIn", from: { path: "src/cart.rs" } } },
      ],
    })
  })

  it("compares a renamed file against its previous path", () => {
    expect(file("src/new_name.py")).toMatchObject({
      diff: { status: "renamed", previousPath: "src/old_name.py" },
      syntax: { status: "analyzed", units: [{ qualifiedName: "greet", change: { kind: "modified", weight: "semantic" } }] },
    })
  })
})
