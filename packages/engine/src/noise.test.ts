import { describe, expect, it } from "vitest"
import { classifyNoise } from "./noise.ts"

describe("classifyNoise", () => {
  it.each([
    { path: "Cargo.lock", content: undefined, kind: "lockfile" },
    { path: "web/pnpm-lock.yaml", content: undefined, kind: "lockfile" },
    { path: "vendor/github.com/x/y.go", content: undefined, kind: "vendored" },
    { path: "libs/third_party/zlib/inflate.c", content: undefined, kind: "vendored" },
    { path: "static/app.min.js", content: undefined, kind: "generated" },
    { path: "api/user_pb2.py", content: undefined, kind: "generated" },
    { path: "src/__generated__/schema.ts", content: undefined, kind: "generated" },
    { path: "src/schema.ts", content: "// @generated by codegen\nexport type A = 1\n", kind: "generated" },
    { path: "gen/types.go", content: "// Code generated by protoc-gen-go. DO NOT EDIT.\npackage x\n", kind: "generated" },
    { path: "src/bindings.rs", content: "/* automatically generated by rust-bindgen */\n", kind: "generated" },
    { path: "src/types.ts", content: "// Auto-generated file\n", kind: "generated" },
    { path: "src/main.rs", content: "fn main() {}\n", kind: undefined },
  ])("classifies $path as $kind", ({ path, content, kind }) => {
    expect(classifyNoise(path, content)?.kind).toBe(kind)
  })

  it("ignores markers below the file header", () => {
    const content = `${"line\n".repeat(10)}// DO NOT EDIT notices are written by the generator below\n`
    expect(classifyNoise("tools/codegen.ts", content)).toBeNull()
  })

  it("does not treat a file named like a vendored directory as vendored", () => {
    expect(classifyNoise("src/vendor", undefined)).toBeNull()
  })
})
